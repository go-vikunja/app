import 'package:vikunja_domain/vikunja_domain.dart';

Project sampleProject({
  required int id,
  required String title,
  int parent = 0,
  double position = 0,
  bool favorite = false,
  bool archived = false,
  String hexColor = '',
  String identifier = '',
}) => Project(
  id: id,
  title: title,
  parentProjectId: parent,
  position: position,
  isFavorite: favorite,
  isArchived: archived,
  hexColor: hexColor,
  identifier: identifier,
);

Label sampleLabel({
  required int id,
  required String title,
  String hexColor = '',
}) => Label(id: id, title: title, hexColor: hexColor);

Task sampleTask({
  required int id,
  required String title,
  int projectId = 1,
  DateTime? due,
  DateTime? start,
  DateTime? end,
  DateTime? doneAt,
  bool done = false,
  TaskPriority priority = TaskPriority.unset,
  double percentDone = 0,
  List<Label> labels = const [],
  List<User> assignees = const [],
  List<TaskReminder> reminders = const [],
  Duration repeatAfter = Duration.zero,
  RepeatMode repeatMode = RepeatMode.afterAmount,
  bool favorite = false,
  String? identifier,
  String description = '',
  double position = 0,
}) => Task(
  id: id,
  title: title,
  projectId: projectId,
  index: id,
  identifier: identifier ?? '-$id',
  dueDate: due?.toUtc(),
  startDate: start?.toUtc(),
  endDate: end?.toUtc(),
  doneAt: doneAt?.toUtc(),
  done: done,
  priority: priority,
  percentDone: percentDone,
  labels: labels,
  assignees: assignees,
  reminders: reminders,
  repeatAfter: repeatAfter,
  repeatMode: repeatMode,
  isFavorite: favorite,
  description: description,
  position: position,
);
