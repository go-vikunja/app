  apiV2,
  sessionRefresh,
  oauthPkce,
  websocket,
  bulkCreateTasks,
  pendingEmail,
  byIndexRedirect,
  localAuth,
  ldapAuth,
  openIdConnect,
  registration,
  linkSharing,
  taskAttachments,
  taskComments,
  totp,
  caldav,
  webhooks,
  publicTeams,
  userDeletion,
  emailReminders,
  backgroundUpload,
  backgroundUnsplash,
  timeTracking,
  adminPanel,
  auditLogs,
  userInvites,
}
